  `IsSigProvRestricted` tinyint(4) NOT NULL,
  PRIMARY KEY (`SheetFieldNum`),
  KEY `SheetNum` (`SheetNum`),
  KEY `FieldType` (`FieldType`),
  KEY `SheetNumFieldType` (`SheetNum`,`FieldType`),
  KEY `SheetFieldDefNum` (`SheetFieldDefNum`)
) ENGINE=MyISAM DEFAULT CHARSET=utf8 COLLATE=utf8_general_ci;
